
# Polymorphism Through Operator Overloading (Advanced)
# Scenario: The + operator behaves differently depending on the data type.

print(10 + 20)

print("Hello " + "World")

print([1, 2] + [3, 4])


# The same + operator performs different operations:
# - Integers: Addition.
# - Strings: Concatenation.
# - Lists: Combining elements.