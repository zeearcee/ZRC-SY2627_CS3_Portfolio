# Polymorphism means many forms. It allows one method call or interface to produce different behaviors depending on the object.

# Method Overriding happens when a child class provides its own implementation of a method that is already defined in its parent class.

# Think of it this way:
# - Overriding is the technique.
# - Polymorphism is the behavior or capability achieved through that technique.


# Polymorphism is not about using a loop. It is about different objects having different behaviors when responding to the same method or interface.